const fmt = (x, d = 1) => (x === null || x === undefined ? '—' : Number(x).toFixed(d));
const pct = (x, d = 0) => (x === null || x === undefined ? '—' : `${(100 * x).toFixed(d)}%`);
const clamp01 = (x) => Math.min(1, Math.max(0, x));

// ===========================================================================
// CANDIDATE consistency curves (NOT approved; parameters are the existing
// provisional role anchors plus one documented provisional ceiling C = 1.0,
// i.e. rel IQR = 100% — a declared hard ceiling, not a population benchmark).
// All candidates: s(excellent) = 100, strictly decreasing in x, bounded [0,100].
// ===========================================================================

const CEILING = 1.0; // provisional hard ceiling: rel IQR of 100% scores 0

/** C1 log-anchored ramp: s = 100·(ln C − ln x)/(ln C − ln e). Zero only at the ceiling. */
function c1LogRamp(x, e) {
  if (x <= e) return 100;
  if (x >= CEILING) return 0;
  return 100 * clamp01((Math.log(CEILING) - Math.log(x)) / (Math.log(CEILING) - Math.log(e)));
}

/** C2 exponential decay anchored so the poor anchor still scores 25: s = 100·exp(−k(x−e)), k = ln4/(p−e). */
function c2Exponential(x, e, p) {
  const k = Math.log(4) / (p - e);
  return 100 * clamp01(Math.exp(-k * (x - e)));
}

/** C3 reciprocal: s = 100·e/x (clamped at 100). No floor; 0 approached asymptotically. */
function c3Reciprocal(x, e) {
  return 100 * clamp01(e / x);
}

/** C4 piecewise soft floor: current slope between anchors but poor maps to floor f=25, then a shallow linear tail to 0 at the ceiling. */
function c4Piecewise(x, e, p, f = 25) {
  if (x <= e) return 100;
  if (x <= p) return f + (100 - f) * ((p - x) / (p - e));
  if (x >= CEILING) return 0;
  return f * ((CEILING - x) / (CEILING - p));
}

const CANDIDATES = [
  ['C1 log-ramp', (x, a) => c1LogRamp(x, a.excellent)],
  ['C2 exponential', (x, a) => c2Exponential(x, a.excellent, a.poor)],
  ['C3 reciprocal', (x, a) => c3Reciprocal(x, a.excellent)],
  ['C4 piecewise', (x, a) => c4Piecewise(x, a.excellent, a.poor)],
];

