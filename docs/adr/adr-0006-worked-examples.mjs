// ===========================================================================
// CANDIDATE automatic-goal lifecycle rule (NOT approved; pure functions here)
// ===========================================================================
//
// Eligible distance population (unchanged from ratings-2): broader full-swing
// cohort on premium-flat, suspected wrong-club excluded, positive carries.
// Per-visit aggregate u_v = P80(carries_v), defined only for visits with
// n_v >= 10 eligible carries.
//
// initialGoal: n >= 10 eligible carries (ANY number of visits, including one)
//              -> provisional goal g0 = round(P90 of all eligible carries).
// upward rule: let T0 = (date, time, id) tuple of the last session in the
//              current goal's calibration window. Q = non-archived sessions
//              with tuple > T0, n_v >= 10, and equipment consistent with the
//              goal. Trigger when |Q| >= 3 AND sum(n_v) >= 30 AND
//              median(u_v) >= g + max(3 m, 3% of g). New goal g' =
//              round(median(u_v)), effective for sessions after max tuple(Q).
//              Never downward. Manual override always wins.

const MIN_GOAL_SAMPLES = 10;
const MIN_TRIGGER_VISITS = 3;
const MIN_TRIGGER_CARRIES = 30;
const ABS_THRESHOLD_M = 3;
const REL_THRESHOLD = 0.03;

const p90 = (values) => quantile(values, 0.9);
const perVisitP80 = (carries) => (carries.length >= MIN_GOAL_SAMPLES ? quantile(carries, 0.8) : null);
const median = (values) => quantile(values, 0.5);
const roundM = (x) => Math.round(x);

function initialGoal(visits) {
  const all = visits.flatMap((v) => v.carries);
  const n = all.length;
  if (n < MIN_GOAL_SAMPLES) return null;
  return { valueM: roundM(p90(all)), n, visits: visits.length, provisional: true };
}

function upwardCheck(goalValueM, establishedTuple, postVisits) {
  const Q = postVisits.filter((v) => v.tuple > establishedTuple && v.archived !== true && v.carries.length >= MIN_GOAL_SAMPLES && v.equipmentOk !== false);
  const us = Q.map((v) => perVisitP80(v.carries)).filter((u) => u !== null);
  const nSum = Q.reduce((s, v) => s + v.carries.length, 0);
  const threshold = Math.max(ABS_THRESHOLD_M, REL_THRESHOLD * goalValueM);
  const med = us.length ? median(us) : null;
  const triggered = Q.length >= MIN_TRIGGER_VISITS && nSum >= MIN_TRIGGER_CARRIES && med !== null && med >= goalValueM + threshold;
  return {
    qualifyingVisits: Q.length,
    carries: nSum,
    perVisitU: us.map((u) => fmt(u)),
    medianU: med,
    thresholdM: threshold,
    requiredM: fmt(goalValueM + threshold),
    triggered,
    newGoalM: triggered ? roundM(med) : null,
  };
}

// Deterministic visit builder: exactly n carries — a linear offset ramp from
// -9 to +9.5 shifted so the sample P80 lands exactly on the requested value
// (P80 via the real `quantile`) — so worked examples read cleanly, the stated
// n is the n actually scored, and output stays byte-for-byte reproducible.
function visitWithP80(n, u, date, time = null, id = null, archived = false, equipmentOk = true) {
  if (n < 2) throw new Error('visit needs at least 2 carries');
  const offs = Array.from({ length: n }, (_, i) => -9 + (18.5 * i) / (n - 1));
  const base = u - quantile(offs, 0.8);
  const carries = offs.map((o) => Math.max(1, base + o));
  return {
    tuple: `${date}T${time ?? '00:00'}#${id ?? date}`,
    date, time, id, archived, equipmentOk,
    carries,
    n: carries.length,
  };
}

